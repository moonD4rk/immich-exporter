package exporter

import (
	"errors"
	"fmt"
	"slices"
	"strings"
	"unicode/utf8"
)

//go:generate go run gen.go

// groups orders the sections of the metrics reference.
var groups = []group{
	groupExporter, groupServer, groupUpkeep, groupAssets, groupCameras, groupPlaces,
	groupPeople, groupUsers, groupAlbums, groupLibrary, groupJobs,
}

const (
	referenceStart = "<!-- Generated by `go generate ./internal/exporter` from the metric descriptors: edit those, not this section. -->"
	referenceEnd   = "<!-- End of the generated section. -->"
)

// Reference lists every exported metric by group, as the Markdown tables of docs/metrics.md.
func Reference() string {
	var b strings.Builder
	for _, g := range groups {
		rows := [][]string{{"Metric", "Labels", "Description"}}
		for _, m := range metrics {
			if m.group != g {
				continue
			}
			labels := "—"
			if len(m.labels) > 0 {
				labels = "`" + strings.Join(m.labels, "`, `") + "`"
			}
			rows = append(rows, []string{"`" + m.name + "`", labels, strings.ReplaceAll(m.help, "|", `\|`)})
		}
		fmt.Fprintf(&b, "### %s\n\n%s\n", g, table(rows))
	}
	return b.String()
}

// table lays rows out the way Prettier does with --prose-wrap never, so formatting the file leaves it as generated:
// columns aligned when the table fits in 80 columns, cells unpadded when it doesn't.
func table(rows [][]string) string {
	widths := make([]int, len(rows[0]))
	total := 1
	for i := range widths {
		widths[i] = 3
		for _, row := range rows {
			widths[i] = max(widths[i], utf8.RuneCountInString(row[i]))
		}
		total += widths[i] + 3
	}
	if total > 80 {
		clear(widths)
	}
	var b strings.Builder
	line := func(cells []string, pad string) {
		for i, cell := range cells {
			b.WriteString("| " + cell + strings.Repeat(pad, max(0, widths[i]-utf8.RuneCountInString(cell))) + " ")
		}
		b.WriteString("|\n")
	}
	line(rows[0], " ")
	line(slices.Repeat([]string{"---"}, len(widths)), "-")
	for _, row := range rows[1:] {
		line(row, " ")
	}
	return b.String()
}

// UpdateReference returns doc, the text of docs/metrics.md, with its generated section replaced by Reference.
func UpdateReference(doc string) (string, error) {
	head, rest, ok := strings.Cut(doc, referenceStart)
	_, tail, closed := strings.Cut(rest, referenceEnd)
	if !ok || !closed {
		return "", errors.New("the metrics reference markers are missing")
	}
	return head + referenceStart + "\n\n" + Reference() + referenceEnd + tail, nil
}
